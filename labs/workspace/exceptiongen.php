<?php
// Moved from exceptiongen.php (original). Adapted for Dev_lab: inline CLI helpers + local exceptions path.

global $path;

// Check if we are inside Docker or on Local Mac
if (file_exists('/.dockerenv')) {
    // We are inside Docker
    $path = '/var/www/labs/htdocs/src/lib/exceptions/';
} else {
    // We are on Local Mac: Use a relative path to stay inside your project
    $path = realpath(__DIR__ . '/../htdocs/src/lib/exceptions/');
}

// Ensure the path is valid and ends with a slash
$path = rtrim($path, '/') . '/';
// --- UPDATED TEMPLATE TO MATCH IMAGE (DocBlock style /**) ---
$template = '<?php

/**
 * Generated by Exception Generator
 * @branch <%branch%>
 * @user <%user%>
 * @date <%date%>
 */

class <%class%> extends Exception {

    protected $message = "<%message%>";
    protected $code = <%code%>;

    public function __construct() {
        parent::__construct($this->message, $this->code);
    }

    public function __toString() {
        return __CLASS__ . ": [{$this->code}]: {$this->message}\n";
    }

}';
// -----------------------------------------------------------

if (!function_exists('primary')) {
    function primary($msg) { echo "\033[1;34m{$msg}\033[0m\n"; }
    function success($msg) { echo "\033[0;32m{$msg}\033[0m\n"; }
    function error($msg) { echo "\033[0;31m{$msg}\033[0m\n"; }
    function startsWith($haystack, $needle) { return strncmp($haystack, $needle, strlen($needle)) === 0; }
    function endsWith($haystack, $needle) { return $needle === '' || substr($haystack, -strlen($needle)) === $needle; }
}

/**
 * Validates the Class Name from user input
 */
function getClass() {
    global $path;
    $class = readline('Class Name: ');
    // Regex for PascalCase
    $r = preg_match('/^[A-Z][a-z]+(?:[A-Z][a-z]+)*$/', $class, $matches);
    if ($r == 1) {
        if (!endsWith($class, "Exception")) {
            error("Class name must end with 'Exception'");
            return false;
        }
        if (file_exists($path . $class . ".class.php")) {
            error("File already exists. Try again with a different name.");
            return false;
        }
        success("That's good.. Let's proceed.");
        return $class;
    } else {
        error("Invalid class name. Please enter a valid PascalCase name.");
        return false;
    }
}

/**
 * Validates the Exception Message from user input
 */
function getMessage() {
    $message = readline('Exception Message: ');
    if (strlen($message) < 16 || !preg_match("/^[A-Za-z,;'\s]+[.?!]$/", $message)) {
        error("Invalid error message. Your message must be greater than 16 characters and end with punctuation.");
        return false;
    } else {
        return $message;
    }
}

/**
 * Automatically generates the next Exception Code [Custom Logic]
 */
function getAutoCode() {
    global $path;
    $files = glob($path . "*.class.php");
    // Starts at 1000 if no files exist, otherwise increments by 1
    return 1000 + count($files) > 0 ? 1000 + count($files) : 1000;
}

// --- Execution Logic ---

primary("Tom Lab Exception Generator starting...");

$class = false;
while (!$class) {
    $class = getClass();
}

$message = false;
while (!$message) {
    $message = getMessage();
}

// Auto-generating code
$code = getAutoCode();

// Replacing placeholders in template
$template = str_replace('<%class%>', $class, $template);
$template = str_replace('<%message%>', $message, $template);
$template = str_replace('<%code%>', $code, $template);
$template = str_replace('<%user%>', exec('id -un'), $template);
$template = str_replace('<%date%>', date("F jS, Y H:i:s", time()), $template);

// Safe Git Branch replacement (Fixes previous error)
$branch = @exec('git rev-parse --abbrev-ref HEAD');
$template = str_replace('<%branch%>', $branch ?: 'none', $template);

echo "\n" . $template . "\n\n";

// Writing the file and performing syntax check
$filePath = $path . $class . ".class.php";
// Ensure directory exists before writing
if (!is_dir($path)) {
     mkdir($path, 0777, true);
}

if (file_put_contents($filePath, $template)) {
    // Syntax check using PHP CLI
    $check = exec("php -l " . escapeshellarg($filePath));
    if (startsWith($check, "No syntax errors detected")) {
        success("Generated file successfully: $filePath");
    } else {
        error("File generated but contains syntax errors!");
    }
} else {
    error("Unable to generate exception. Check folder permissions and config path.");
}
